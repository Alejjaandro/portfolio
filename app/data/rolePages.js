export const roleSlugs = Object.keys(rolePages)

export function getRoleBySlug(slug) {
  return rolePages[slug]
}

export function getRoleByAnySlug(slug) {
  for (const key of roleSlugs) {
    const page = rolePages[key]
    if (page.slugEn === slug || page.slugEs === slug) {
      return { key, page }
    }
  }
  return null
}

export function getOppositeRoleUrl(currentSlug, currentLocale) {
  const result = getRoleByAnySlug(currentSlug)
  if (!result) return '/'
  const { page } = result
  if (currentLocale === 'en') {
    return `/es/${page.slugEs}`
  }
  return `/${page.slugEn}`
}
